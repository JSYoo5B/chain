package compiler

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/scanner"
	"go/token"
	"reflect"
	"strings"

	"github.com/JSYoo5B/chain/internal/dsl/frontend"
)

type outputSegment struct {
	start    int
	original frontend.Span
}

// mappedOutput tracks source positions before formatting. SourcePos printing
// then preserves original filenames and lines through Go's //line directives.
// Go's printer does not preserve exact original columns after formatting.
type mappedOutput struct {
	bytes.Buffer
	source   *frontend.Source
	filename string
	segments []outputSegment
}

func (o *mappedOutput) insert(anchor int, text string) {
	if text == "" {
		return
	}
	o.segments = append(o.segments, outputSegment{o.Len(), frontend.Span{Start: anchor, End: anchor}})
	o.WriteString(text)
}

func (o *mappedOutput) printf(anchor int, text string, args ...any) {
	o.insert(anchor, fmt.Sprintf(text, args...))
}

func (o *mappedOutput) copy(span frontend.Span) {
	if span.Start == span.End {
		return
	}
	o.segments = append(o.segments, outputSegment{o.Len(), span})
	o.WriteString(o.source.Text(span))
}

func (o *mappedOutput) position(offset int) token.Position {
	for i := len(o.segments) - 1; i >= 0; i-- {
		segment := o.segments[i]
		if segment.start <= offset {
			original := segment.original.Start
			if segment.original.End > original {
				original += min(offset-segment.start, segment.original.End-original)
			}
			return o.source.Position(original)
		}
	}
	return o.source.Position(0)
}

func (o *mappedOutput) formatted() ([]byte, error) {
	data := o.Bytes()
	parsedPositions := token.NewFileSet()
	file, err := parser.ParseFile(parsedPositions, "generated.go", data,
		parser.ParseComments|parser.AllErrors|parser.SkipObjectResolution)
	if err != nil {
		var diagnostics scanner.ErrorList
		if list, ok := err.(scanner.ErrorList); ok {
			for _, diagnostic := range list {
				diagnostics.Add(o.position(diagnostic.Pos.Offset), diagnostic.Msg)
			}
			diagnostics.Sort()
			return nil, diagnostics.Err()
		}
		return nil, err
	}
	// SourcePos uses physical token positions, not //line-adjusted metadata.
	// Rebase AST positions into a file containing the original DSL source.
	positions := token.NewFileSet()
	physical := positions.AddFile(o.filename, -1, o.source.Size())
	physical.SetLinesForContent([]byte(o.source.Text(frontend.Span{Start: 0, End: o.source.Size()})))
	generated := parsedPositions.File(file.Package)
	seen := map[ast.Node]bool{}
	posType := reflect.TypeOf(token.NoPos)
	visit := func(node ast.Node) bool {
		if node == nil || seen[node] {
			return false
		}
		seen[node] = true
		value := reflect.ValueOf(node).Elem()
		for i := 0; i < value.NumField(); i++ {
			field := value.Field(i)
			if field.Type() == posType && field.CanSet() {
				pos := token.Pos(field.Int())
				if pos.IsValid() {
					field.SetInt(int64(physical.Pos(o.position(generated.Offset(pos)).Offset)))
				}
			}
		}
		return true
	}
	ast.Inspect(file, visit)
	for _, group := range file.Comments {
		ast.Inspect(group, visit)
		for _, comment := range group.List {
			if strings.HasPrefix(comment.Text, "//line ") || strings.HasPrefix(comment.Text, "/*line ") {
				// Same-length ordinary comment: user directives must not override
				// the compiler's physical .chain source mapping.
				comment.Text = comment.Text[:2] + "Line " + comment.Text[7:]
			}
		}
	}
	var result bytes.Buffer
	config := printer.Config{Mode: printer.UseSpaces | printer.TabIndent | printer.SourcePos, Tabwidth: 8}
	if err := config.Fprint(&result, positions, file); err != nil {
		return nil, err
	}
	formatted, err := format.Source(result.Bytes())
	if err != nil {
		return nil, err
	}
	return append([]byte("// Code generated by chain-gen. DO NOT EDIT.\n\n"), formatted...), nil
}
