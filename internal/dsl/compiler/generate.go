package compiler

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"sort"
	"strconv"

	"github.com/JSYoo5B/chain/internal/dsl/frontend"
)

// Compile parses and analyzes a DSL file, then emits formatted Go source.
// Imports and Go type correctness are validated when the generated package is
// built; compilation never executes prerequisite code or action constructors.
func Compile(filename string, text []byte) ([]byte, error) {
	file, err := frontend.Parse(filename, text)
	if err != nil {
		return nil, err
	}
	program, err := Analyze(file)
	if err != nil {
		return nil, err
	}
	return generate(program)
}

func generate(program *Program) ([]byte, error) {
	var output bytes.Buffer
	output.WriteString("// Code generated by chain-gen. DO NOT EDIT.\n\n")
	output.WriteString(program.File.Source.Text(program.File.HeaderSpan))
	if len(program.Workflows) == 0 {
		return format.Source(output.Bytes())
	}
	used := usedIdentifiers(program)
	runtimeName := freshName("_chain", used)
	fmt.Fprintf(&output, "\nimport %s %q\n\n", runtimeName, "github.com/JSYoo5B/chain")
	for _, workflow := range program.Workflows {
		w := workflow.Syntax
		var typeCode bytes.Buffer
		if err := format.Node(&typeCode, token.NewFileSet(), w.Go.StateType); err != nil {
			return nil, err
		}
		state := typeCode.String()
		local := freshName("_workflow", used)
		fmt.Fprintf(&output, "func %s%s *%s.Workflow[%s] {", w.Constructor.Name,
			program.File.Source.Text(w.Parameters.Span), runtimeName, state)
		if w.Prerequisite != nil {
			output.WriteString(program.File.Source.Text(w.Prerequisite.Content))
			// Preserve a statementless label at the end of the original block.
			// The newline also prevents a trailing // comment hiding generated code.
			output.WriteString("\n;\n")
		}
		fmt.Fprintf(&output, "%s := %s.NewWorkflow[%s](%s", local, runtimeName, state, strconv.Quote(w.Name.Name))
		for _, node := range workflow.Nodes {
			fmt.Fprintf(&output, ", %s", node.Name.Name)
		}
		output.WriteString(")\n")
		for _, node := range workflow.Nodes {
			if len(node.Directions) == 0 {
				fmt.Fprintf(&output, "%s.SetRunPlan(%s, %s.TerminationPlan[%s]())\n", local, node.Name.Name, runtimeName, state)
				continue
			}
			fmt.Fprintf(&output, "%s.SetRunPlan(%s, %s.RunPlan[%s]{\n", local, node.Name.Name, runtimeName, state)
			directions := make([]string, 0, len(node.Directions))
			for direction := range node.Directions {
				directions = append(directions, direction)
			}
			sort.Strings(directions)
			for _, direction := range directions {
				target := node.Directions[direction].Name
				if target == "end" {
					target = fmt.Sprintf("%s.Terminate[%s]()", runtimeName, state)
				}
				fmt.Fprintf(&output, "%s: %s,\n", strconv.Quote(direction), target)
			}
			output.WriteString("})\n")
		}
		fmt.Fprintf(&output, "return %s\n}\n\n", local)
	}
	return format.Source(output.Bytes())
}

// Avoid introducing an import or local variable that shadows user identifiers
// in parameters, state types, prerequisite code, or workflow declarations.
func usedIdentifiers(program *Program) map[string]bool {
	used := map[string]bool{}
	collect := func(root ast.Node) {
		ast.Inspect(root, func(node ast.Node) bool {
			if name, ok := node.(*ast.Ident); ok {
				used[name.Name] = true
			}
			return true
		})
	}
	collect(program.File.Header)
	for _, workflow := range program.Workflows {
		w := workflow.Syntax
		used[w.Constructor.Name], used[w.Name.Name] = true, true
		collect(w.Go.Parameters)
		collect(w.Go.StateType)
		if w.Go.Prerequisite != nil {
			collect(w.Go.Prerequisite)
		}
		for _, node := range workflow.Nodes {
			used[node.Name.Name] = true
		}
	}
	return used
}

func freshName(base string, used map[string]bool) string {
	name := base
	for i := 1; used[name]; i++ {
		name = base + strconv.Itoa(i)
	}
	used[name] = true
	return name
}
